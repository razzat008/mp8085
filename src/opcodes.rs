use crate::AddressingMode;
use std::{collections::HashMap, sync::LazyLock};

#[derive(Debug, Clone)]
#[allow(dead_code)]
pub struct OpCode {
    pub code: u8,
    pub mnemonic: String,
    pub len: u8,
    pub cycles: u8,
    pub mode: AddressingMode,
}

#[allow(dead_code)]
impl OpCode {
    fn new(
        code: u8,
        mnemonic: impl Into<String>,
        len: u8,
        cycles: u8,
        mode: AddressingMode,
    ) -> Self {
        Self {
            code,
            mnemonic: mnemonic.into(),
            len,
            cycles,
            mode,
        }
    }
}

